"""Contract snapshot of the public `aegis` CLI surface (ADR 0005 AD-6, defense #43).

`cli_tree.json` is generated by walking the real argparse parser. It records
every command, subcommand, flag, positional, default, choice and nargs, how each
command name resolves, the command registry (name, aliases, category, help) and
the pointers printed for removed commands. Any change to the public CLI shows up
as a diff of that file and is reviewed with the code that caused it.

Regenerate after an intended surface change, from the repository root:

    PYTHONPATH=. python3 tests/contract/test_cli_contract.py --write
"""
from __future__ import annotations

import argparse
import json
import shlex
import sys
from pathlib import Path
from typing import Any, Dict, List

SNAPSHOT = Path(__file__).with_name("cli_tree.json")
SUPPRESS = "==SUPPRESS=="

_ACTION_KINDS = {
    "_StoreAction": "store",
    "_StoreTrueAction": "store_true",
    "_StoreFalseAction": "store_false",
    "_StoreConstAction": "store_const",
    "_AppendAction": "append",
    "_AppendConstAction": "append_const",
    "_CountAction": "count",
    "_HelpAction": "help",
    "_VersionAction": "version",
    "_SubParsersAction": "parsers",
}


def _value(value: Any) -> Any:
    if value is argparse.SUPPRESS:
        return SUPPRESS
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, (list, tuple)):
        return [_value(v) for v in value]
    if callable(value):
        return getattr(value, "__name__", type(value).__name__)
    return repr(value)


def _action(action: argparse.Action) -> Dict[str, Any]:
    kind = type(action).__name__
    entry: Dict[str, Any] = {
        "kind": _ACTION_KINDS.get(kind, kind),
        "flags": list(action.option_strings),
        "dest": action.dest,
        "default": _value(action.default),
        "nargs": _value(action.nargs),
        "required": bool(action.required),
    }
    if action.choices is not None and not isinstance(action, argparse._SubParsersAction):
        entry["choices"] = _value(list(action.choices))
    if action.type is not None:
        entry["type"] = _value(action.type)
    if action.const is not None:
        entry["const"] = _value(action.const)
    return entry


def _parser_tree(parser: argparse.ArgumentParser) -> Dict[str, Any]:
    arguments: List[Dict[str, Any]] = []
    commands: Dict[str, Any] = {}
    for action in parser._actions:
        arguments.append(_action(action))
        if isinstance(action, argparse._SubParsersAction):
            names_by_parser: Dict[int, List[str]] = {}
            parsers: Dict[int, argparse.ArgumentParser] = {}
            # Insertion order is name first, then its aliases.
            for name, sub in action._name_parser_map.items():
                names_by_parser.setdefault(id(sub), []).append(name)
                parsers[id(sub)] = sub
            for key, names in names_by_parser.items():
                node = _parser_tree(parsers[key])
                node["aliases"] = names[1:]
                commands[names[0]] = node
    tree: Dict[str, Any] = {"arguments": arguments}
    if commands:
        tree["commands"] = commands
    return tree


def build_cli_contract() -> Dict[str, Any]:
    from aegis_cli import cli
    from aegis_cli.registry import get_default_registry

    parser = cli._build_parser(prog="aegis")
    tree = _parser_tree(parser)
    # Which registered command each accepted spelling dispatches to.
    resolution = {}
    for name, node in tree.get("commands", {}).items():
        for spelling in [name, *node["aliases"]]:
            cmd = get_default_registry().get(spelling)
            resolution[spelling] = cmd.name if cmd is not None else None
    registry = [
        {
            "name": cmd.name,
            "aliases": list(cmd.aliases),
            "category": cmd.category.value,
            "help": cmd.help,
        }
        for cmd in sorted(get_default_registry().list_commands(), key=lambda c: c.name)
    ]
    contract: Dict[str, Any] = {
        "parser": tree,
        "command_resolution": resolution,
        "registry": registry,
    }
    removed = getattr(cli, "REMOVED_COMMANDS", None)
    if removed is not None:
        contract["removed_commands"] = {name: removed[name] for name in sorted(removed)}
    return contract


def _render(contract: Dict[str, Any]) -> str:
    return json.dumps(contract, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def test_cli_surface_matches_snapshot():
    expected = SNAPSHOT.read_text(encoding="utf-8")
    actual = _render(build_cli_contract())
    assert actual == expected, (
        "The aegis CLI surface changed. If intended, regenerate the snapshot with\n"
        "    PYTHONPATH=. python3 tests/contract/test_cli_contract.py --write\n"
        "and review the diff of tests/contract/cli_tree.json."
    )


def test_installed_git_hook_command_parses_as_check_hook():
    """The argv the git pre-commit hook execs must stay a valid `check --hook` call (H7 floor)."""
    from aegis_cli.cli import _build_parser
    from aegis_cli.hooks.management import generate_hook_block

    block = generate_hook_block("/opt/py/bin/python3")
    argvs = []
    for line in block.splitlines():
        tokens = shlex.split(line.strip()) if line.strip().startswith("exec ") else []
        if "aegis_cli" in tokens:
            argvs.append(tokens[tokens.index("aegis_cli") + 1:])
    assert argvs, f"no `-m aegis_cli` exec line in the hook block:\n{block}"
    parser = _build_parser(prog="aegis")
    for argv in argvs:
        ns = parser.parse_args(argv)
        assert ns.command == "check"
        assert ns.hook is True


def test_top_level_help_lists_every_registered_command(capsys):
    import pytest
    from aegis_cli.cli import main
    from aegis_cli.registry import get_default_registry

    with pytest.raises(SystemExit) as exc:
        main(["--help"], prog="aegis")
    assert exc.value.code == 0
    out = capsys.readouterr().out
    for cmd in get_default_registry().list_commands():
        assert f"  {cmd.name} " in out, f"`aegis --help` does not list {cmd.name}:\n{out}"
        assert cmd.help in out


if __name__ == "__main__":
    if sys.argv[1:] != ["--write"]:
        sys.exit("usage: PYTHONPATH=. python3 tests/contract/test_cli_contract.py --write")
    SNAPSHOT.write_text(_render(build_cli_contract()), encoding="utf-8")
    print(f"wrote {SNAPSHOT}")
