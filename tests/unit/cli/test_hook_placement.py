"""Where `aegis hook install` puts its block in an existing pre-commit hook, and when
`hook status` can tell that the block never runs (release review, seams finding).

The block goes right after the shebang and does not `exec`, so a hook whose own
lines end in `exec` or `exit` (the pre-commit framework's, many husky setups) still
runs the check first and its own lines after. A hook that is not a shell script is
refused unless --force. The previous file is copied to ~/.aegis/backups/<stamp>/
before it is edited.
"""
from __future__ import annotations

import os
import shlex
import stat
import subprocess
import sys
from pathlib import Path

import pytest

from aegis_cli.cli import main
from aegis_cli.hooks.management import (
    CURRENT_HOOK_FORMAT_VERSION,
    _AEGIS_HOOK_END,
    _AEGIS_HOOK_START,
    generate_hook_block,
    hook_status,
    install_hook,
)

POSIX = pytest.mark.skipif(os.name == "nt", reason="runs the hook through /bin/sh")

FRAMEWORK_HOOK = '#!/usr/bin/env bash\n# File generated by pre-commit\nexec true "$@"\n'
PYTHON_HOOK = '#!/usr/bin/env python3\nprint("lint")\n'
NO_EVAL = "---\nid: no-eval\ntype: invariant\nenforcement: gate\nforbid_ast:\n  calls: [eval]\n---\n# No eval\n"


def _git(repo: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=str(repo), capture_output=True, text=True, timeout=120)


def _repo(path: Path) -> Path:
    path.mkdir(parents=True)
    for args in (("init", "-q", "-b", "main"), ("config", "user.email", "t@example.com"), ("config", "user.name", "T")):
        assert _git(path, *args).returncode == 0
    return path


def _hook(repo: Path) -> Path:
    return repo / ".git" / "hooks" / "pre-commit"


def _write_hook(repo: Path, text: str) -> Path:
    hook = _hook(repo)
    hook.parent.mkdir(parents=True, exist_ok=True)
    hook.write_text(text, encoding="utf-8")
    hook.chmod(0o755)
    return hook


def _backups(home: Path) -> list:
    root = home / ".aegis" / "backups"
    return sorted(root.rglob("pre-commit")) if root.is_dir() else []


@pytest.fixture
def home():
    return Path(os.environ["HOME"])  # the CLI conftest's isolated HOME


# ── the block itself ─────────────────────────────────────────────────────────

def test_the_block_never_execs_and_stops_the_hook_only_when_the_check_fails():
    block = generate_hook_block("/opt/py/bin/python3", import_root="/opt/site")
    commands = [line.strip() for line in block.splitlines() if not line.strip().startswith("#")]
    assert not any(line.startswith("exec ") for line in commands)
    run = [line for line in commands if "check --hook" in line]
    assert len(run) == 1
    tokens = shlex.split(run[0])
    assert tokens[:2] == ["$AEGIS_PYTHON", "-I"]
    assert run[0].endswith("check --hook || exit $?")


def test_the_new_block_is_a_new_format():
    assert CURRENT_HOOK_FORMAT_VERSION == 6
    assert f"aegis-hook-format: {CURRENT_HOOK_FORMAT_VERSION}" in generate_hook_block("/usr/bin/python3", "/opt/site")


# ── placement ────────────────────────────────────────────────────────────────

def test_the_block_goes_right_after_the_shebang_of_an_existing_hook(tmp_path):
    repo = _repo(tmp_path / "r")
    hook = _write_hook(repo, FRAMEWORK_HOOK)

    assert install_hook(repo, python=sys.executable)

    text = hook.read_text(encoding="utf-8")
    lines = text.splitlines()
    assert lines[0] == "#!/usr/bin/env bash"
    assert lines[1] == _AEGIS_HOOK_START
    assert text.endswith(_AEGIS_HOOK_END + '\n# File generated by pre-commit\nexec true "$@"\n')


def test_a_hook_without_a_shebang_gains_one_before_the_block(tmp_path):
    repo = _repo(tmp_path / "r")
    hook = _write_hook(repo, "echo mine\n")

    assert install_hook(repo, python=sys.executable)

    text = hook.read_text(encoding="utf-8")
    assert text.startswith("#!/bin/sh\n" + _AEGIS_HOOK_START + "\n")
    assert text.endswith(_AEGIS_HOOK_END + "\necho mine\n")


def test_an_appended_block_moves_first_and_reinstalling_changes_nothing(tmp_path):
    repo = _repo(tmp_path / "r")
    old = generate_hook_block(sys.executable).replace(
        f"aegis-hook-format: {CURRENT_HOOK_FORMAT_VERSION}", "aegis-hook-format: 5")
    hook = _write_hook(repo, "#!/bin/sh\necho before\nexec true\n" + old + "echo after\n")

    assert install_hook(repo, python=sys.executable)
    first = hook.read_text(encoding="utf-8")
    assert first == "#!/bin/sh\n" + generate_hook_block(sys.executable) + "echo before\nexec true\necho after\n"

    assert install_hook(repo, python=sys.executable)
    assert hook.read_text(encoding="utf-8") == first


@POSIX
def test_a_hook_that_ends_in_exec_still_blocks_a_violating_commit(tmp_path):
    repo = _repo(tmp_path / "r")
    rule = repo / ".aegis" / "rules" / "invariants" / "no-eval.md"
    rule.parent.mkdir(parents=True)
    rule.write_text(NO_EVAL, encoding="utf-8")
    _write_hook(repo, FRAMEWORK_HOOK)
    assert install_hook(repo)
    (repo / "app.py").write_text("x = eval(input())\n", encoding="utf-8")
    _git(repo, "add", "-A")

    proc = _git(repo, "commit", "-m", "evil")

    assert proc.returncode != 0, proc.stdout + proc.stderr
    assert "forbid_ast:no-eval: app.py" in proc.stdout + proc.stderr
    assert _git(repo, "rev-parse", "--verify", "-q", "HEAD").returncode != 0  # nothing was committed


@POSIX
def test_the_users_own_lines_still_run_after_a_passing_check(tmp_path):
    repo = _repo(tmp_path / "r")
    marker = tmp_path / "user-ran"
    _write_hook(repo, f"#!/bin/sh\necho user-hook > {shlex.quote(str(marker))}\nexit 0\n")
    assert install_hook(repo)
    (repo / "app.py").write_text("x = 1\n", encoding="utf-8")
    _git(repo, "add", "app.py")

    proc = _git(repo, "commit", "-m", "clean")

    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert marker.read_text(encoding="utf-8") == "user-hook\n"


# ── refusal of a hook that is not a shell script ─────────────────────────────

@pytest.mark.parametrize("dry_run", [False, True], ids=["install", "dry-run"])
def test_a_hook_that_is_not_a_shell_script_is_refused(tmp_path, capsys, home, dry_run):
    repo = _repo(tmp_path / "r")
    hook = _write_hook(repo, PYTHON_HOOK)

    assert install_hook(repo, python=sys.executable, dry_run=dry_run) is False

    assert hook.read_text(encoding="utf-8") == PYTHON_HOOK
    err = capsys.readouterr().err
    assert str(hook) in err
    assert "python3" in err
    assert "--force" in err
    assert _backups(home) == []


def test_aegis_hook_install_exits_1_for_a_python_hook(tmp_path, monkeypatch, capsys):
    repo = _repo(tmp_path / "r")
    hook = _write_hook(repo, PYTHON_HOOK)
    monkeypatch.chdir(repo)

    assert main(["hook", "install"]) == 1

    assert hook.read_text(encoding="utf-8") == PYTHON_HOOK
    err = capsys.readouterr().err
    assert str(hook) in err and "--force" in err


def test_a_binary_hook_is_refused(tmp_path, capsys):
    repo = _repo(tmp_path / "r")
    hook = _hook(repo)
    hook.write_bytes(b"\x7fELF\x02\x01\x01\x00\xff\xfe")

    assert install_hook(repo, python=sys.executable) is False

    assert hook.read_bytes() == b"\x7fELF\x02\x01\x01\x00\xff\xfe"
    assert "--force" in capsys.readouterr().err


def test_force_replaces_a_python_hook_after_backing_it_up(tmp_path, home):
    repo = _repo(tmp_path / "r")
    hook = _write_hook(repo, PYTHON_HOOK)

    assert install_hook(repo, python=sys.executable, force=True)

    assert hook.read_text(encoding="utf-8") == "#!/bin/sh\n" + generate_hook_block(sys.executable)
    [backup] = _backups(home)
    assert backup.read_text(encoding="utf-8") == PYTHON_HOOK


# ── backup before editing ────────────────────────────────────────────────────

def test_an_existing_hook_is_backed_up_before_it_is_edited(tmp_path, home):
    repo = _repo(tmp_path / "r")
    _write_hook(repo, FRAMEWORK_HOOK)

    assert install_hook(repo, python=sys.executable)

    [backup] = _backups(home)
    assert backup.parent.parent == home / ".aegis" / "backups"
    assert backup.read_text(encoding="utf-8") == FRAMEWORK_HOOK
    if os.name != "nt":
        assert stat.S_IMODE(backup.stat().st_mode) == 0o600


def test_no_backup_for_a_new_hook_or_an_unchanged_one(tmp_path, home):
    repo = _repo(tmp_path / "r")

    assert install_hook(repo, python=sys.executable)
    assert install_hook(repo, python=sys.executable)

    assert _backups(home) == []


@POSIX
def test_no_edit_without_a_backup(tmp_path, home, capsys):
    repo = _repo(tmp_path / "r")
    hook = _write_hook(repo, FRAMEWORK_HOOK)
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    (home / ".aegis").symlink_to(elsewhere, target_is_directory=True)

    assert install_hook(repo, python=sys.executable) is False

    assert hook.read_text(encoding="utf-8") == FRAMEWORK_HOOK
    assert "back" in capsys.readouterr().err
    assert list(elsewhere.iterdir()) == []


# ── hook status: can the block run? ──────────────────────────────────────────

def _status_of(tmp_path: Path, text: str) -> dict:
    repo = _repo(tmp_path / "r")
    _write_hook(repo, text)
    return hook_status(repo)


def test_a_fresh_install_is_reachable(tmp_path):
    repo = _repo(tmp_path / "r")
    assert install_hook(repo, python=sys.executable)
    st = hook_status(repo)
    assert (st["reachable"], st["unreachable_reason"]) == (True, None)


def test_no_hook_is_not_reachable_and_says_nothing_more(tmp_path):
    st = hook_status(_repo(tmp_path / "r"))
    assert st["status"] == "not_installed"
    assert (st["reachable"], st["unreachable_reason"]) == (False, None)


def test_a_block_after_a_top_level_exec_is_unreachable(tmp_path):
    st = _status_of(tmp_path, FRAMEWORK_HOOK + generate_hook_block(sys.executable))
    assert st["status"] == "installed"
    assert st["reachable"] is False
    assert "line 3" in st["unreachable_reason"]
    assert "exec" in st["unreachable_reason"]


def test_a_block_after_a_top_level_exit_is_unreachable(tmp_path):
    st = _status_of(tmp_path, "#!/bin/sh\nrun-linters\nexit 0\n" + generate_hook_block(sys.executable))
    assert st["reachable"] is False
    assert "line 3" in st["unreachable_reason"]


def test_a_top_level_exec_after_a_function_is_still_found(tmp_path):
    st = _status_of(tmp_path, "#!/bin/sh\nlint() {\n  exit 1\n}\nexec true\n" + generate_hook_block(sys.executable))
    assert st["reachable"] is False
    assert "line 5" in st["unreachable_reason"]


def test_a_block_in_a_python_hook_is_unreachable(tmp_path):
    st = _status_of(tmp_path, PYTHON_HOOK + generate_hook_block(sys.executable))
    assert st["reachable"] is False
    assert "python3" in st["unreachable_reason"]


@POSIX
def test_a_hook_git_cannot_execute_is_unreachable(tmp_path):
    repo = _repo(tmp_path / "r")
    assert install_hook(repo, python=sys.executable)
    _hook(repo).chmod(0o644)
    st = hook_status(repo)
    assert st["reachable"] is False
    assert "executable" in st["unreachable_reason"]


@pytest.mark.parametrize("before", [
    '[ -n "$SKIP_LINT" ] && exit 0\n',
    "if [ -f .skip ]; then\n  exit 0\nfi\n",
    "if [ -f .skip ]; then exit 0; fi\n",
    "exec >/tmp/hook.log 2>&1\n",
    "lint() {\n  exit 1\n}\n",
    "echo 'exit now'\n",
], ids=["conditional", "if-block", "one-line-if", "redirect-only", "function", "quoted"])
def test_an_exit_that_does_not_end_the_hook_keeps_it_reachable(tmp_path, before):
    st = _status_of(tmp_path, "#!/bin/sh\n" + before + generate_hook_block(sys.executable))
    assert (st["reachable"], st["unreachable_reason"]) == (True, None)


def test_hook_status_text_names_an_unreachable_block(tmp_path, monkeypatch, capsys):
    repo = _repo(tmp_path / "r")
    _write_hook(repo, FRAMEWORK_HOOK + generate_hook_block(sys.executable))
    monkeypatch.chdir(repo)

    assert main(["hook", "status"]) == 0

    out = capsys.readouterr().out
    assert "never runs" in out
    assert "aegis hook install" in out
